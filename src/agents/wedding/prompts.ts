/**
 * 婚纱/礼服姿势提示词。
 * 参考图顺序：图 1 新娘、图 2 新郎、图 3 姿势线稿。
 * 按 Seedream 提示词指南：编号指代参考图，两段式——先写保留哪些参考元素，再写生成画面；
 * 编辑指令指明对象，并显式写「保持……不变」。
 * 优先级：人物身份 > 姿势与互动 > 人体比例 > 服装 > 构图与背景。
 * 该接口没有独立 negative_prompt 字段，禁止项直接写在正文里。
 * 成片要叠到背景色/背景图/贴纸上，所以只生成人物和服装，不生成摄影场景。
 */

const IDENTITY =
  "以图3的人物姿势为参考，生成一张真实自然的婚纱摄影作品，将新娘塑造为图1中的人，将新郎塑造为图2中的人。严格保留图1和图2中人物的身份特征，使生成后的两人能够清晰辨认出与原照片中的本人一致：保留各自独特的五官特征、面部辨识度和整体气质，不要将人物替换成相似的陌生人。";

export function buildWeddingPosePrompt(outfit: string, aspect: string, request = ""): string {
  const requestLine =
    request.trim() === ""
      ? []
      : [`用户补充要求：${request.trim()}（与前面的要求冲突时，以前面的要求为准）`];

  return [
    IDENTITY,
    `根据参考姿势合理生成两人的完整身体及服装：${outfit}`,
    "自然适配人物的头部姿态、面部角度、表情、透视关系及光照，允许合理重构面部结构，使面部与姿态协调一致，不要生硬复制原始照片的面部形状或角度；确保眼睛、鼻子、嘴巴、下颌及面部轮廓协调自然，避免五官错位、脸部扭曲、表情僵硬、面部比例异常及不自然的面部结构。",
    "两人的姿势、身体动作、肢体关系及整体构图尽可能遵循图3，人物互动自然，身体比例协调，避免肢体变形；只参考图3的姿势、动作、互动和左右站位，不保留它的头身比、腿长和人物高度。",
    "两人均为高挑修长的写真模特体态：约7.5–8头身，腿长（胯到脚底）约占身高一半，腰线偏高，身体纵向舒展，头部大小自然；避免矮胖、短腿、五五分、躯干压缩、横向膨胀，不要照搬线稿的矮比例。礼服自然垂坠，避免裙摆横向扩张。",
    ...requestLine,
    "生成真实的婚纱摄影质感：皮肤冷白透亮、细腻真实，妆容自然，光影柔和，呈现自然的皮肤纹理和细腻的服装材质，最终画面自然、真实、优雅，像真实摄影师拍摄的婚纱照片，而非 AI 生成的图像。",
    `人物完整呈现，构图舒展，头顶适当留白，脚部不裁切；图3有坐具才生成坐具。画面比例 ${aspect}；只保留人物、服装及姿势所需坐具；不要背景、地面、投影、文字、水印、Logo、边框。`,
  ].join("\n");
}

export function buildWeddingPoseEditPrompt(instruction: string, aspect: string): string {
  return [
    "参考图1是当前成片。",
    `只修改：${instruction}。`,
    "保持人物身份、脸型、骨相、五官、发型、服装、姿势、构图和画面风格不变；不换人、不增减人物。",
    `输出 ${aspect} 的婚纱礼服写真照片；不要添加背景、文字、水印、Logo 或边框。`,
  ].join("\n");
}
