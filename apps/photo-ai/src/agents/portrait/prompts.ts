/**
 * AI 职业形象照提示词。
 *
 * 参考图顺序：图 1 至图 N 是同一个人不同角度的照片（1–3 张）。
 * 目标：生成现代、年轻、精致的商业职业形象照。
 * 成片需叠加到背景上，因此仅生成人物，输出透明 PNG。
 *
 * 核心要求：
 * - 保留人物身份，确保面部辨识度。
 * - 允许商业人像级自然美颜，改善面容、皮肤和牙齿状态。
 * - 现代、年轻、精致的服装造型和摄影风格。
 * - 姿势自然、松弛、有现代感。
 * - 人体比例协调，人物边缘干净，透明背景。
 */

function referenceLine(faceCount: number) {
  if (faceCount === 1) return "图1是人物参考照片。";
  return `图1至图${faceCount}是同一个人不同角度的参考照片，综合参考这些照片中的人物特征。`;
}

const IDENTITY =
  "将参考照片中的人物塑造成现代职业肖像的主角。严格保留人物身份特征，使生成后的人物能够清晰辨认出与原照片中的本人一致，保留独特的五官特征、面部辨识度、脸型及整体气质，不要将人物替换成相似的陌生人。";

const STYLING =
  "根据人物特征与所选风格，设计年轻、现代、精致的都市职业造型。服装具有当代时尚审美，注重现代剪裁、利落廓形、优质面料、协调的搭配层次与精致细节，避免老气、刻板、过度正式的传统职业装。整体造型参考 Apple 风格的人物肖像审美及当代简约时尚，呈现年轻、自然、干净、克制而有品位的视觉效果。";

const PHOTOGRAPHY =
  "采用高品质现代商业人像摄影风格，参考 Apple 人物肖像的视觉审美：简洁、明亮、自然、克制、精致。采用柔和自然的光线与细腻的光影塑形，画面清爽通透，色彩干净，人物具有自然的精神状态和真实的情绪表达。避免老式影楼风、传统企业宣传照、刻板证件照、沉闷色调、过度修饰及生硬摆拍。";
const BEAUTY =
  "对人物面部进行精致的商业人像美化与自然修饰，在严格保留本人身份、五官特征及面部辨识度的前提下，改善面部状态。肤色均匀通透，淡化明显瑕疵、暗沉、痘印、黑眼圈及疲惫感，改善皮肤粗糙和不均匀质感，保留自然细腻的皮肤纹理。牙齿整洁洁白，牙齿形态自然，微笑时牙齿呈现健康洁净的状态。眼神明亮，面部精神饱满，唇色自然，妆容精致清淡，呈现年轻、健康、清爽、有精神的状态，避免过度磨皮、塑料皮肤、夸张美颜、失真五官和不自然的美妆效果。";

export interface PortraitLook {
  attire: string;
  mood: string;
  pose: string;
  composition: string;
}

export function buildPortraitPrompt(
  faceCount: number,
  look: PortraitLook,
  aspect: string,
  request = "",
): string {
  const requestLine =
    request.trim() === ""
      ? []
      : [`用户补充要求：${request.trim()}（与前面的要求冲突时，以前面的要求为准）`];

  return [
    referenceLine(faceCount),
    IDENTITY,
    STYLING,
    BEAUTY,
    `服装：${look.attire}`,
    `姿势：${look.pose}。表情与气质：${look.mood}。`,
    `构图：${look.composition}；按所选构图自然裁切，头顶留出适当空间，不要刚好切在下巴、腋下或膝盖等关节处。`,
    "自然适配人物的头部姿态、面部角度、表情、透视关系及光照，使面部与姿态协调一致；确保眼睛、鼻子、嘴巴、下颌及面部轮廓协调自然，避免五官错位、脸部扭曲、表情僵硬、面部比例异常及不自然的面部结构。",
    "人物比例自然，头肩关系协调，不要拉长脖子或缩小头部；服装贴合身形，褶皱和材质真实。",
    ...requestLine,
    PHOTOGRAPHY,
    `画面比例 ${aspect}；只保留人物和服装，背景为真正带 Alpha 通道的透明 PNG；人物和服装边缘干净自然，不要贴纸白边、白色描边、轮廓光晕、背景、地面、投影、文字、水印、Logo、边框。`,
  ].join("\n");
}

